"""REPORT.md: parts found, per-pass accuracy, final accuracy, open problems."""
from collections import Counter
from pathlib import Path

import numpy as np

from .common import NOTE_NAMES, jdump, note_name
from . import gpio


def ascii_tab(track, b0, nb, meter, spb=4):
    """ASCII tab for bars [b0, b0+nb) of a parsed GP track (one column per 16th)."""
    cols = nb * meter * spb
    grid = [["---"] * cols for _ in range(6)]
    for n in track["notes"]:
        c = int(round((n["t"] - b0 * meter) * spb))
        if 0 <= c < cols:
            grid[n["string"]][c] = str(n["fret"]).ljust(3, "-")
    names = ["e", "B", "G", "D", "A", "E"]
    lines = []
    for s in range(6):
        w_ = meter * spb
        row = "|".join("".join(grid[s][i:i + w_]) for i in range(0, cols, w_))
        lines.append(f"{names[s]}|{row}|")
    return "\n".join(lines)


def describe(track, part, meter, nbars):
    ns = track["notes"]
    if not ns:
        return dict(n_notes=0)
    ps = np.array([n["p"] for n in ns])
    on = Counter(round(n["t"] * 4) for n in ns)
    chords = sum(1 for v in on.values() if v >= 2) / len(on)
    bars_active = sorted(set(n["bar"] for n in ns))
    pos = Counter(int(round(n["t"] * 4)) % (meter * 4) for n in ns)
    on_beat = sum(v for k, v in pos.items() if k % 4 == 0) / len(ns)
    on_8th = sum(v for k, v in pos.items() if k % 2 == 0) / len(ns)
    pcs = Counter(NOTE_NAMES[p % 12] for p in ps)
    frets = np.array([n["fret"] for n in ns])
    strings = Counter(n["string"] + 1 for n in ns)
    open_frac = float(np.mean(frets == 0))
    density = len(on) / max(1, len(bars_active))
    texture = ("chordal (strummed/stabs)" if chords > 0.6 else
               "arpeggiated / fingerpicked with double-stops" if chords > 0.2 else "single-note line (melody / arpeggio)")
    rhythm = ("mostly 16ths" if density > 7 else "mostly 8ths" if density > 4 else "sparse / sustained")
    return dict(n_notes=len(ns), n_onsets=len(on), bars=[bars_active[0] + 1, bars_active[-1] + 1],
                range=f"{note_name(int(ps.min()))}-{note_name(int(ps.max()))}", median=note_name(int(np.median(ps))),
                onsets_per_bar=round(density, 2), chord_fraction=round(chords, 2), on_beat=round(on_beat, 2),
                on_8th=round(on_8th, 2), top_pitch_classes=" ".join(f"{k}" for k, _ in pcs.most_common(5)),
                fret_range=f"{int(frets.min())}-{int(frets.max())}", median_fret=float(np.median(frets)),
                open_string_fraction=round(open_frac, 2), busiest_strings=[s for s, _ in strings.most_common(3)],
                texture=texture, rhythm=rhythm)


def _fmt(x):
    return "—" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.3f}"


def write(ctx, final, mode, meta, R, sep, P, passes, ev, fstats, progs, pngs, runtime):
    final = Path(final)
    song = gpio.read(final)
    meter = song["meter"]
    parts = P["parts"]
    L = []
    w = L.append
    w(f"# {meta.get('title', '')} — {meta.get('artist', '')}: auto-transcription report\n")
    w(f"Generated by `mp3gp` in {runtime / 60:.1f} min. Input: `{ctx.inp}`.\n")
    w("## Summary\n")
    w(f"* **Guitar parts found: {len(parts)}** → {len(parts)} tracks in `{final.name}`")
    for p in parts:
        w(f"  * {p['name']}: bars {p['bars'][0] + 1}–{p['bars'][1]}")
    w(f"* Tuning: standard (E A D G B E, assumed). Meter **{R['meter']}/4**, tempo **{R['bpm_median']:.1f} BPM** "
      f"(per-bar range {R['bpm_min']:.1f}–{R['bpm_max']:.1f}; GP tempo map: "
      f"{', '.join(str(t) for t in sorted(set(song['tempos'])))}), {len(R['bars'])} bars, bar 1 at "
      f"{R['bars'][0]['start']:.3f}s.")
    kc = ", ".join(f"{k} ({r:.2f})" for r, k in R["key_candidates"])
    w(f"* Key: **{R['key']}** (Krumhansl correlation; candidates {kc}).")
    fs = ev["summary"]
    w(f"* Final accuracy (best pass {passes[[r.get('best') for r in passes].index(True)]['pass_'] if any(r.get('best') for r in passes) else '?'}): "
      + "; ".join(f"{k}: score {_fmt(v['score'])} (chroma {_fmt(v['chroma'])}, pitch-F {_fmt(v['pitch_f'])}, onset-F {_fmt(v['onset_f'])})"
                  for k, v in fs.items()))
    w("")
    if mode == "ensemble":
        w("**Mode: ensemble (estimated parts).** The audio cannot cleanly split the guitars (they overlap in "
          "register and the doubled part sits partly in the centre), so the parts are *estimated*: one note pool is "
          "transcribed from the all-guitars stem (Basic Pitch + a learned ghost-note classifier), then distributed "
          "over the roles found below with playability constraints (per onset: lead parts <=2 notes, "
          "arpeggio/rhythm part <=4 new notes, every part's notes must be fingerable within a 5-fret span with <=4 "
          "fingers). The spatial energy share of a note in each part stem is only a hint for which role gets it. "
          "The loop optimises the COMBINED playback against the all-guitars stem and the mix; the per-part-vs-stem "
          "scores are diagnostics only.\n")
    w("## Guitar parts\n")
    w("Model separators (all four candidates) only give one *all-guitars* stem — none splits guitar from guitar. "
      "Parts were therefore found from stereo placement over time: PCA primary/ambient decomposition per "
      "time-frequency tile, a centre pan mask on the primary, and L-only / R-only tile masks to classify the rest "
      "per bar as one-sided (`right`/`left`) or `double` (both sides at similar level, low inter-channel coherence "
      "= double-tracked takes panned hard L/R).\n")
    w("| part | bars | stereo evidence (median dB re. all-guitars, active bars) | GM patch | notes | range | texture | rhythm |")
    w("|---|---|---|---|---|---|---|---|")
    E = P["bar_energy"]
    descs = {}
    for i, p in enumerate(parts):
        tr = song["tracks"][i]
        d = describe(tr, p, meter, len(R["bars"]))
        descs[p["id"]] = d
        bars = [b for a, e in p.get("segments", [p["bars"]]) for b in range(a, e)]
        ev_s = {k: float(np.median([E[b][k] for b in bars])) for k in ("centre", "wide", "L_only", "R_only")}
        evs = f"centre {ev_s['centre']:.1f}, wide {ev_s['wide']:.1f}, L-only {ev_s['L_only']:.1f}, R-only {ev_s['R_only']:.1f}"
        w(f"| **{p['name']}** | {p['bars'][0] + 1}–{p['bars'][1]} | {evs} | {progs.get(p['id'])} | {d.get('n_notes', 0)} | "
          f"{d.get('range', '')} (median {d.get('median', '')}) | {d.get('texture', '')}; chord fraction {d.get('chord_fraction', '')} | "
          f"{d.get('rhythm', '')}; {d.get('onsets_per_bar', '')} onsets/bar |")
    w("")
    for i, p in enumerate(parts):
        d = descs[p["id"]]
        if not d.get("n_notes"):
            continue
        w(f"### {p['name']}\n")
        w(f"* Plays bars {d['bars'][0]}–{d['bars'][1]}; {d['n_notes']} notes in {d['n_onsets']} onsets; register {d['range']}, "
          f"most used pitch classes {d['top_pitch_classes']}.")
        w(f"* Fretboard: frets {d['fret_range']} (median {d['median_fret']:.0f}), open strings {100 * d['open_string_fraction']:.0f}% "
          f"of notes, busiest strings {d['busiest_strings']}; {100 * d['on_beat']:.0f}% of notes on the beat, "
          f"{100 * d['on_8th']:.0f}% on 8th positions.")
        st = fstats.get(p["id"], {})
        if st:
            w(f"* Fingering DP: max stretch {st.get('max_span')} frets, {100 * st.get('frac_span_gt3', 0):.1f}% of fretted "
              f"events need a >3-fret span, mean hand shift {st.get('mean_shift', 0):.2f} frets/event, "
              f"chord-shape consistency {100 * st.get('shape_consistency', 1):.0f}% over {st.get('chord_pitchsets')} "
              f"chord pitch-sets, {st.get('dropped_unplayable', 0)} unplayable notes dropped.")
        b0 = d["bars"][0] - 1
        w(f"\nFirst bars (bar {b0 + 1}–{b0 + 2}, 3 characters = one 16th):\n\n```\n{ascii_tab(song['tracks'][i], b0, 2, meter)}\n```\n")
    w("## Separation candidates\n")
    w("Scored per bar: *leak* = time-frequency overlap with the drum stem, *loss* = harmonic energy left in "
      "`mix − stem` (guitar the separator threw away). Lower is better for both; best stem chosen per 4-bar section.\n")
    w("| candidate | mean leak dB | mean loss dB | sections chosen |")
    w("|---|---|---|---|")
    cc = Counter(sep["choice"])
    for k, v in sep["candidates"].items():
        w(f"| {k} | {v['mean_leak_db']:.1f} | {v['mean_loss_db']:.1f} | {cc.get(k, 0) // 4} |")
    w("")
    w("## Re-synthesis loop: accuracy per pass\n")
    w("Each pass renders the whole tab (read back from the .gp5) with FluidSynth and scores every bar: "
      "chroma = CQT-chroma cosine, pitch-F = frame multi-pitch F (Basic Pitch on render vs reference), "
      "onset-F = onset F-measure (±50 ms); score = mean. Parts are scored against their own separated stem; "
      "`full_vs_guitars` / `full_vs_mix` compare the summed render with the all-guitar stem / the original mix "
      "(faded-out bars excluded). " + (
        "Then the worst ~30% of bars by combined score are re-estimated (ghost-classifier thresholds 0.2/0.5/0.7, "
        "strong-onset-only pool, register-based role reassignment, drop-weakest / octave-fix / add-missing edits, "
        "copying a matching repeated bar); every candidate is rendered with ALL parts together and kept only if its "
        "mean(guitars, mix) bar score beats the current bar by >0.01 without losing >0.03 pitch-F vs the guitars "
        "stem. Each candidate passes the same per-part playability constraints." if mode == "ensemble" else
        "Then the worst ~20% bars per part are redone (alternative decodes, salience-guided octave/drop/add edits, "
        "borrowing a matching repeated bar), each candidate rendered and scored in isolation, and kept only if it "
        "beats the current bar by >0.01 without losing >0.03 pitch-F.") + " Full numbers: `passes.json`.\n")
    keys = ["full_vs_guitars", "full_vs_mix"] + [p["id"] for p in parts]
    w("Columns: score (c = chroma / p = pitch-F / o = onset-F). " + ("Objective = mean of full_vs_guitars and "
      "full_vs_mix; per-part columns are each track vs its separated stem (diagnostic)." if mode == "ensemble" else
      "Objective = mean part score.") + "\n")
    w("| pass | " + " | ".join(keys) + " | objective | bars redone |")
    w("|---|" + "---|" * (len(keys) + 2))
    for r in passes:
        cells = []
        for k in keys:
            s = r["summary"].get(k)
            cells.append(f"{s['score']:.3f} (c {s['chroma']:.2f} / p {s['pitch_f']:.2f} / o {s['onset_f']:.2f})" if s else "—")
        red = r.get("redone_bars")
        red = ", ".join(f"{k.replace('_', ' ')}: {v}" for k, v in red.items()) if red else (r.get("stopped") or "")
        mark = " ★" if r.get("best") else ""
        w(f"| {r['pass_']}{mark} | " + " | ".join(cells) + f" | {r['mean_part_score']:.4f} | {red} |")
    w("\n★ = pass kept as final. Edits accepted (all passes): " +
      ", ".join(f"{k} ×{v}" for k, v in Counter(c["edit"].split("_bar")[0] if c["edit"].startswith("copy") else c["edit"]
                                                 for r in passes for c in r.get("changes", [])).most_common()) + "\n")
    w("### Worst bars after the final pass\n")
    for k in ["full_vs_guitars", "full_vs_mix"] + [p["id"] for p in parts]:
        rows = [r for r in ev["per_bar"][k] if not np.isnan(r["score"]) and R["bars"][r["bar"]].get("audible", True)]
        rows.sort(key=lambda r: r["score"])
        w(f"* {k}: " + ", ".join(f"bar {r['bar'] + 1} ({r['score']:.2f})" for r in rows[:8]))
    w("")
    notes = ctx.w("analyst_notes.md")
    if notes.exists():
        w(notes.read_text())
    w("## Open problems (generic)\n")
    w("* Scores are relative to *separated* stems, which still contain bleed (other guitars' reverb, cymbals); "
      "a perfect tab would not reach 1.0, and the absolute numbers are best read as pass-to-pass trends.")
    w("* Parts are split by stereo placement. Unison passages of two parts in the same pan position, or two parts "
      "sharing a double-tracked pair, cannot be separated this way; notes of a double-tracked part that line up "
      "in time collapse into the centre mask and are re-assigned by energy share only.")
    w("* Basic Pitch is a piano-ish general model: palm mutes, slides, bends, harmonics and vibrato are not "
      "detected; the tab contains plain notes only (let-ring marks where notes sustain).")
    w("* The fingering DP checks ringing conflicts against the previous event only and assumes standard tuning; "
      "an alternate tuning would show up as awkward shapes / many 'unplayable' drops.")
    w("* FluidSynth GM guitars are not the recorded tones (effects, amp, reverb); chroma and Basic-Pitch-based "
      "pitch-F are fairly timbre-robust, onset-F less so.")
    w("")
    w("## Files\n")
    w(f"* `{final.name}` — Guitar Pro 5 tab, {len(parts)} tracks, tempo map, let-ring, section markers")
    w("* `tab/tab-page*.png`, `tab/tab.pdf`, `tab/tab.ly` — LilyPond engraving (tab + rhythm per track)")
    w("* `comparison.wav` — ~30 s of the original, 1 s gap, then the same section played from the tab")
    w("* `comparison_side_by_side.wav` — same section, original left / tab right; "
      "`comparison_side_by_side_full_song.mp3` — whole song")
    w("* `parts/*_separated_stem.mp3`, `parts/*_stem_L_vs_tab_R.mp3` — each part's stem and stem-vs-tab check")
    w("* `passes.json` — per-pass, per-part, per-metric accuracy and every accepted bar edit")
    Path(ctx.o("REPORT.md")).write_text("\n".join(L) + "\n")
